using System.Globalization;
using System.Net;
using System.Text;
using System.Text.RegularExpressions;
using EmailStudio.Models;

namespace EmailStudio.Services;

/// <summary>
/// Converts an EmailTemplate into a self-contained, strongly-typed C# static class
/// that generates complete HTML email strings using string interpolation and parameterized variables.
/// </summary>
public static class CSharpEmailExporter
{
    private const string TQ = "\"\"\"";

    public static string GetClassName(string? templateName)
    {
        if (string.IsNullOrWhiteSpace(templateName))
            return "CustomEmailTemplate";

        var parts = Regex.Split(templateName, @"[^a-zA-Z0-9]+")
            .Where(p => !string.IsNullOrEmpty(p))
            .Select(p => char.ToUpperInvariant(p[0]) + (p.Length > 1 ? p[1..] : ""))
            .ToArray();

        var name = string.Concat(parts);
        if (string.IsNullOrWhiteSpace(name))
            name = "Custom";

        if (char.IsDigit(name[0]))
            name = "Email" + name;

        if (!name.EndsWith("Template", StringComparison.OrdinalIgnoreCase))
            name += "Template";

        return name;
    }

    public static string EscapeString(string? value)
    {
        if (value is null) return "\"\"";
        return "\"" + value
            .Replace("\\", "\\\\")
            .Replace("\"", "\\\"")
            .Replace("\r", "\\r")
            .Replace("\n", "\\n")
            .Replace("\t", "\\t")
            + "\"";
    }

    private sealed record ParamDef(string PropName, string ParamName, string DefaultValue, string DocComment);

    public static string Export(EmailTemplate t)
    {
        TemplateStore.Validate(t);
        var className = GetClassName(t.Name);
        var vars = BuildVariables(t);

        var sb = new StringBuilder();

        sb.AppendLine("// <auto-generated>");
        sb.AppendLine("// This file was generated by Email Studio.");
        sb.AppendLine($"// Template: {t.Name}");
        sb.AppendLine($"// Category: {t.Category}");
        sb.AppendLine("// </auto-generated>");
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Collections.Generic;");
        sb.AppendLine("using System.Globalization;");
        sb.AppendLine("using System.Linq;");
        sb.AppendLine("using System.Net;");
        sb.AppendLine("using System.Text;");
        sb.AppendLine();
        sb.AppendLine("namespace EmailStudio.Templates;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Static email template generator for '{t.Name}'.");
        sb.AppendLine("/// Generates the complete HTML email string with all texts, images, and links parameterized via variables.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine($"public static class {className}");
        sb.AppendLine("{");

        // 1. Strongly-typed model class
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Model containing all customizable content and style variables for this email template.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public sealed class EmailModel");
        sb.AppendLine("    {");
        foreach (var v in vars)
        {
            sb.AppendLine("        /// <summary>");
            sb.AppendLine($"        /// {v.DocComment}");
            sb.AppendLine("        /// </summary>");
            sb.AppendLine($"        public string {v.PropName} {{ get; set; }} = {EscapeString(v.DefaultValue)};");
            sb.AppendLine();
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        // 2. Overload accepting EmailModel
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Generates the complete HTML email string using the provided model.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public static string Render(EmailModel? model = null)");
        sb.AppendLine("    {");
        sb.AppendLine("        model ??= new EmailModel();");
        sb.AppendLine("        return Render(");
        for (var i = 0; i < vars.Count; i++)
        {
            var comma = i < vars.Count - 1 ? "," : ");";
            sb.AppendLine($"            {vars[i].ParamName}: model.{vars[i].PropName}{comma}");
        }
        sb.AppendLine("    }");
        sb.AppendLine();

        // 3. Alias GenerateHtml(EmailModel)
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Alias for Render(EmailModel) to generate complete HTML email string.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public static string GenerateHtml(EmailModel? model = null) => Render(model);");
        sb.AppendLine();

        // 4. Main Render method with all optional parameters
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Generates the complete HTML email string using string interpolation and parameterized variables.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public static string Render(");
        for (var i = 0; i < vars.Count; i++)
        {
            var comma = (i < vars.Count - 1) ? "," : ")";
            sb.AppendLine($"        string {vars[i].ParamName} = {EscapeString(vars[i].DefaultValue)}{comma}");
        }
        sb.AppendLine("    {");

        // Inside Render method
        sb.AppendLine("        var html = new StringBuilder();");
        sb.AppendLine();
        sb.AppendLine("        // Document Header and Wrapper Table");
        sb.AppendLine($"        html.Append(${TQ}<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" content=\"width=device-width,initial-scale=1\"><title>{{E(pageTitle)}}</title></head><body style=\"margin:0;padding:24px 12px;background:{{backgroundColor}};font-family:Arial,sans-serif;color:{{textColor}}\"><table role=\"presentation\" width=\"100%\" cellspacing=\"0\" cellpadding=\"0\" style=\"border-collapse:collapse\"><tr><td align=\"center\"><table role=\"presentation\" width=\"600\" cellspacing=\"0\" cellpadding=\"0\" style=\"width:100%;max-width:600px;background:{{surfaceColor}};border-collapse:collapse\">{TQ});");
        sb.AppendLine();

        // Render each block
        for (var i = 0; i < t.Blocks.Count; i++)
        {
            var b = t.Blocks[i];
            var idx = i + 1;
            sb.AppendLine($"        // Block {idx}: {b.Type}");
            sb.AppendLine($"        html.Append(${TQ}<tr><td style=\"padding:24px 32px;background:{{blockBackgroundColor_{idx}}};color:{{blockTextColor_{idx}}};font-size:15px;line-height:1.6\">{TQ});");

            switch (b.Type)
            {
                case "header":
                    sb.AppendLine($"        html.Append(${TQ}<table role=\"presentation\" width=\"100%\" cellspacing=\"0\" cellpadding=\"0\" style=\"border-collapse:collapse;margin-bottom:28px\"><tr><td valign=\"middle\">{TQ});");
                    sb.AppendLine("        if (!string.IsNullOrWhiteSpace(brandLogoUrl))");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            html.Append(${TQ}<img src=\"{{E(brandLogoUrl)}}\" alt=\"{{E(brandName)}}\" width=\"40\" height=\"40\" style=\"display:inline-block;width:40px;height:40px;vertical-align:middle;border-radius:10px;margin-right:10px\">{TQ});");
                    sb.AppendLine("        }");
                    sb.AppendLine("        else");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            html.Append(${TQ}<span role=\"img\" aria-label=\"{{E(brandName)}} logo\" style=\"display:inline-block;width:40px;height:40px;line-height:40px;text-align:center;vertical-align:middle;border-radius:11px;background:{{blockAccentColor_{idx}}};color:{{ContrastText(blockAccentColor_{idx})}};font-size:13px;font-weight:bold;letter-spacing:-.4px;margin-right:10px\">{{E(BrandInitials(brandName))}}</span>{TQ});");
                    sb.AppendLine("        }");
                    sb.AppendLine("        if (!string.IsNullOrWhiteSpace(brandWebsiteUrl))");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            html.Append(${TQ}<a href=\"{{E(brandWebsiteUrl)}}\" style=\"vertical-align:middle;color:{{blockTextColor_{idx}}};font-size:14px;font-weight:bold;text-decoration:none\">{{E(brandName)}}</a>{TQ});");
                    sb.AppendLine("        }");
                    sb.AppendLine("        else");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            html.Append(${TQ}<span style=\"vertical-align:middle;color:{{blockTextColor_{idx}}};font-size:14px;font-weight:bold\">{{E(brandName)}}</span>{TQ});");
                    sb.AppendLine("        }");
                    sb.AppendLine($"        html.Append(${TQ}</td><td align=\"right\" style=\"font-size:11px;letter-spacing:1px;color:{{blockAccentColor_{idx}}}\">{{Lines(headerBadge_{idx})}}</td></tr></table>{TQ});");
                    sb.AppendLine($"        html.Append(${TQ}<h1 style=\"font-size:34px;line-height:1.15;letter-spacing:-.7px;margin:0;color:{{blockTextColor_{idx}}}\">{{E(headerTitle_{idx})}}</h1>{TQ});");
                    break;

                case "text":
                    sb.AppendLine($"        if (!string.IsNullOrEmpty(textHeading_{idx}))");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            html.Append(${TQ}<h2 style=\"font-size:21px;line-height:1.3;margin:0 0 12px;color:{{blockTextColor_{idx}}}\">{{E(textHeading_{idx})}}</h2>{TQ});");
                    sb.AppendLine("        }");
                    sb.AppendLine($"        html.Append(${TQ}<div>{{Lines(textBody_{idx})}}</div>{TQ});");
                    break;

                case "button":
                    sb.AppendLine($"        if (!string.IsNullOrWhiteSpace(buttonUrl_{idx}))");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            html.Append(${TQ}<a href=\"{{E(buttonUrl_{idx})}}\" style=\"display:inline-block;background:{{blockAccentColor_{idx}}};color:{{blockTextColor_{idx}}};padding:12px 22px;text-decoration:none;font-weight:bold;border-radius:4px\">{{E(buttonText_{idx})}}</a>{TQ});");
                    sb.AppendLine("        }");
                    sb.AppendLine("        else");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            html.Append(${TQ}<span style=\"display:inline-block;background:{{blockAccentColor_{idx}}};color:{{blockTextColor_{idx}}};padding:12px 22px;font-weight:bold;border-radius:4px\">{{E(buttonText_{idx})}}</span>{TQ});");
                    sb.AppendLine("        }");
                    break;

                case "image":
                    sb.AppendLine($"        if (!string.IsNullOrWhiteSpace(imageUrl_{idx}))");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            html.Append(${TQ}<img src=\"{{E(imageUrl_{idx})}}\" alt=\"{{E(imageAlt_{idx})}}\" width=\"536\" style=\"display:block;width:100%;max-width:536px;height:auto;border-radius:16px\">{TQ});");
                    sb.AppendLine("        }");
                    sb.AppendLine("        else");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            var placeholder_{idx} = Mix(blockAccentColor_{idx}, \"#ffffff\", 0.12);");
                    sb.AppendLine($"            html.Append(${TQ}<table role=\"presentation\" width=\"100%\" cellspacing=\"0\" cellpadding=\"0\" style=\"border-collapse:collapse\"><tr><td bgcolor=\"{{placeholder_{idx}}}\" height=\"205\" valign=\"middle\" style=\"height:205px;padding:28px 32px;background:{{placeholder_{idx}}};border-radius:16px\"><div style=\"font-size:10px;font-weight:bold;letter-spacing:2px;color:{{blockAccentColor_{idx}}}\">{{E(brandName)}} &nbsp; / &nbsp; {{E(imagePlaceholderBadge_{idx})}}</div><div style=\"font-size:23px;line-height:1.25;font-weight:bold;color:#182033;margin-top:14px\">{{E(imageAlt_{idx})}}</div><div style=\"font-size:12px;line-height:1.5;color:#182033;margin-top:10px\">{{E(imagePlaceholderNote_{idx})}}</div></td></tr></table>{TQ});");
                    sb.AppendLine("        }");
                    break;

                case "divider":
                    sb.AppendLine($"        html.Append(${TQ}<hr style=\"border:0;border-top:1px solid {{blockAccentColor_{idx}}};margin:0\">{TQ});");
                    break;

                case "footer":
                    sb.AppendLine($"        html.Append(${TQ}<div style=\"padding:20px 0 15px;border-top:1px solid {{blockAccentColor_{idx}}}\"><span style=\"font-size:13px\">{{E(footerHeading_{idx})}}</span><br><strong style=\"display:inline-block;margin-top:5px;font-size:16px\">{{E(brandSignature)}}</strong></div>{TQ});");
                    sb.AppendLine("        if (!string.IsNullOrWhiteSpace(brandWebsiteUrl))");
                    sb.AppendLine("        {");
                    sb.AppendLine($"            html.Append(${TQ}<div style=\"font-size:12px;margin:0 0 12px\"><a href=\"{{E(brandWebsiteUrl)}}\" style=\"color:{{blockAccentColor_{idx}}}\">{{E(footerVisitLabel_{idx})}} {{E(brandName)}}</a></div>{TQ});");
                    sb.AppendLine("        }");
                    sb.AppendLine($"        html.Append(${TQ}<div style=\"font-size:12px;line-height:1.6;color:{{blockTextColor_{idx}}};opacity:.72\">{{Lines(footerContent_{idx})}}</div>{TQ});");
                    break;

                case "table":
                    sb.AppendLine($"        RenderTable(html, tableHeading_{idx}, tableData_{idx}, tableStyle_{idx}, blockBackgroundColor_{idx}, blockTextColor_{idx}, blockAccentColor_{idx});");
                    break;

                case "bar chart":
                case "comparison chart":
                case "forecast chart":
                case "line chart":
                case "area chart":
                case "pie chart":
                case "doughnut chart":
                    sb.AppendLine($"        RenderChart(html, chartHeading_{idx}, chartData_{idx}, {EscapeString(b.Type)}, blockBackgroundColor_{idx}, blockTextColor_{idx}, blockAccentColor_{idx});");
                    break;
            }

            sb.AppendLine("        html.Append(\"</td></tr>\");");
            sb.AppendLine();
        }

        sb.AppendLine("        html.Append(\"</table></td></tr></table></body></html>\");");
        sb.AppendLine("        return html.ToString();");
        sb.AppendLine("    }");
        sb.AppendLine();

        // 5. Alias GenerateHtml with parameters
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Alias for Render(...) with optional parameters to generate complete HTML email string.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public static string GenerateHtml(");
        for (var i = 0; i < vars.Count; i++)
        {
            var comma = (i < vars.Count - 1) ? "," : ")";
            sb.AppendLine($"        string {vars[i].ParamName} = {EscapeString(vars[i].DefaultValue)}{comma}");
        }
        sb.AppendLine("        => Render(");
        for (var i = 0; i < vars.Count; i++)
        {
            var comma = i < vars.Count - 1 ? "," : ");";
            sb.AppendLine($"            {vars[i].ParamName}: {vars[i].ParamName}{comma}");
        }
        sb.AppendLine();

        // Append helper methods (E, Lines, BrandInitials, ContrastText, Mix, SliceColor, RenderTable, RenderChart)
        AppendHelperMethods(sb);

        sb.AppendLine("}");
        return sb.ToString();
    }

    private static List<ParamDef> BuildVariables(EmailTemplate t)
    {
        var list = new List<ParamDef>
        {
            new("PageTitle", "pageTitle", t.Name, "Document title displayed in browser / email client tab"),
            new("BrandName", "brandName", t.BrandName, "Brand name displayed in header, logo alt, and footer"),
            new("BrandSignature", "brandSignature", t.BrandSignature, "Team sign-off in the email footer"),
            new("BrandLogoUrl", "brandLogoUrl", t.BrandLogoUrl, "URL to brand logo image (leave empty to use initials monogram)"),
            new("BrandWebsiteUrl", "brandWebsiteUrl", t.BrandWebsiteUrl, "Brand website destination link"),
            new("BackgroundColor", "backgroundColor", t.BackgroundColor, "Outer body background color hex"),
            new("SurfaceColor", "surfaceColor", t.SurfaceColor, "Inner email card surface color hex"),
            new("TextColor", "textColor", t.TextColor, "Default body text color hex"),
            new("AccentColor", "accentColor", t.AccentColor, "Default accent theme color hex")
        };

        for (var i = 0; i < t.Blocks.Count; i++)
        {
            var b = t.Blocks[i];
            var idx = i + 1;

            list.Add(new($"BlockBackgroundColor_{idx}", $"blockBackgroundColor_{idx}", b.BackgroundColor, $"Block {idx} ({b.Type}) background color hex"));
            list.Add(new($"BlockTextColor_{idx}", $"blockTextColor_{idx}", b.TextColor, $"Block {idx} ({b.Type}) text color hex"));
            list.Add(new($"BlockAccentColor_{idx}", $"blockAccentColor_{idx}", b.AccentColor, $"Block {idx} ({b.Type}) accent color hex"));

            switch (b.Type)
            {
                case "header":
                    list.Add(new($"HeaderTitle_{idx}", $"headerTitle_{idx}", b.Title, $"Block {idx} header main title"));
                    list.Add(new($"HeaderBadge_{idx}", $"headerBadge_{idx}", b.Content, $"Block {idx} header right-aligned badge/category text"));
                    break;
                case "text":
                    list.Add(new($"TextHeading_{idx}", $"textHeading_{idx}", b.Title, $"Block {idx} section heading"));
                    list.Add(new($"TextBody_{idx}", $"textBody_{idx}", b.Content, $"Block {idx} section body text"));
                    break;
                case "button":
                    list.Add(new($"ButtonText_{idx}", $"buttonText_{idx}", b.Title, $"Block {idx} call-to-action button text"));
                    list.Add(new($"ButtonUrl_{idx}", $"buttonUrl_{idx}", b.Url, $"Block {idx} call-to-action button URL"));
                    break;
                case "image":
                    list.Add(new($"ImageUrl_{idx}", $"imageUrl_{idx}", b.Url, $"Block {idx} image URL"));
                    list.Add(new($"ImageAlt_{idx}", $"imageAlt_{idx}", b.Title, $"Block {idx} image alt text / title"));
                    list.Add(new($"ImagePlaceholderBadge_{idx}", $"imagePlaceholderBadge_{idx}", "IMAGE PREVIEW", $"Block {idx} placeholder badge label"));
                    list.Add(new($"ImagePlaceholderNote_{idx}", $"imagePlaceholderNote_{idx}", "Add an image URL to replace this branded placeholder.", $"Block {idx} placeholder note"));
                    break;
                case "footer":
                    list.Add(new($"FooterHeading_{idx}", $"footerHeading_{idx}", b.Title, $"Block {idx} footer heading"));
                    list.Add(new($"FooterContent_{idx}", $"footerContent_{idx}", b.Content, $"Block {idx} footer disclaimer / notes"));
                    list.Add(new($"FooterVisitLabel_{idx}", $"footerVisitLabel_{idx}", "Visit", $"Block {idx} visit website link prefix"));
                    break;
                case "table":
                    list.Add(new($"TableHeading_{idx}", $"tableHeading_{idx}", b.Title, $"Block {idx} table heading"));
                    list.Add(new($"TableData_{idx}", $"tableData_{idx}", b.Content, $"Block {idx} pipe-separated table rows"));
                    list.Add(new($"TableStyle_{idx}", $"tableStyle_{idx}", b.TableStyle, $"Block {idx} table style: classic, striped, or accent"));
                    break;
                case "bar chart":
                case "comparison chart":
                case "forecast chart":
                case "line chart":
                case "area chart":
                case "pie chart":
                case "doughnut chart":
                    list.Add(new($"ChartHeading_{idx}", $"chartHeading_{idx}", b.Title, $"Block {idx} chart heading"));
                    list.Add(new($"ChartData_{idx}", $"chartData_{idx}", b.Content, $"Block {idx} comma-separated chart rows (label,value)"));
                    break;
            }
        }

        return list;
    }

    private static void AppendHelperMethods(StringBuilder sb)
    {
        sb.AppendLine("    #region Rendering Helpers");
        sb.AppendLine();
        sb.AppendLine("    private static string E(string? value) => WebUtility.HtmlEncode(value ?? string.Empty);");
        sb.AppendLine("    private static string Lines(string? value) => E(value).Replace(\"\\r\\n\", \"\\n\").Replace(\"\\n\", \"<br>\");");
        sb.AppendLine();
        sb.AppendLine("    private static string BrandInitials(string brandName)");
        sb.AppendLine("    {");
        sb.AppendLine("        var words = brandName.Split(' ', StringSplitOptions.RemoveEmptyEntries);");
        sb.AppendLine("        if (brandName == \"ABC Company\") return \"ABC\";");
        sb.AppendLine("        return words.Length > 1");
        sb.AppendLine("            ? string.Concat(words.Take(2).Select(word => char.ToUpperInvariant(word[0])))");
        sb.AppendLine("            : brandName[..Math.Min(2, brandName.Length)].ToUpperInvariant();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static string ContrastText(string color)");
        sb.AppendLine("    {");
        sb.AppendLine("        static double Linear(int value) { var c = value / 255.0; return c <= 0.04045 ? c / 12.92 : Math.Pow((c + 0.055) / 1.055, 2.4); }");
        sb.AppendLine("        var r = Convert.ToInt32(color.Substring(1, 2), 16);");
        sb.AppendLine("        var g = Convert.ToInt32(color.Substring(3, 2), 16);");
        sb.AppendLine("        var b = Convert.ToInt32(color.Substring(5, 2), 16);");
        sb.AppendLine("        return 0.2126 * Linear(r) + 0.7152 * Linear(g) + 0.0722 * Linear(b) > 0.179 ? \"#000000\" : \"#ffffff\";");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static string Mix(string foreground, string background, double amount)");
        sb.AppendLine("    {");
        sb.AppendLine("        static int Channel(string color, int offset) => Convert.ToInt32(color.Substring(offset, 2), 16);");
        sb.AppendLine("        int Blend(int offset) => (int)Math.Round(Channel(foreground, offset) * amount + Channel(background, offset) * (1 - amount));");
        sb.AppendLine("        return $\"#{Blend(1):x2}{Blend(3):x2}{Blend(5):x2}\";");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static string SliceColor(string accent, int index)");
        sb.AppendLine("    {");
        sb.AppendLine("        var factor = new[] { 1.0, .78, .60, .43, .28, .15 }[index % 6];");
        sb.AppendLine("        var r = Convert.ToInt32(accent.Substring(1, 2), 16);");
        sb.AppendLine("        var g = Convert.ToInt32(accent.Substring(3, 2), 16);");
        sb.AppendLine("        var b = Convert.ToInt32(accent.Substring(5, 2), 16);");
        sb.AppendLine("        return $\"#{(int)(255 - (255 - r) * factor):x2}{(int)(255 - (255 - g) * factor):x2}{(int)(255 - (255 - b) * factor):x2}\";");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static string F(double value) => value.ToString(\"0.##\", CultureInfo.InvariantCulture);");
        sb.AppendLine();
        sb.AppendLine("    private static void RenderTable(StringBuilder html, string title, string content, string tableStyle, string backgroundColor, string textColor, string accentColor)");
        sb.AppendLine("    {");
        sb.AppendLine($"        html.Append(${TQ}<h2 style=\"font-size:19px;margin:0 0 14px;color:{{textColor}}\">{{E(title)}}</h2><table width=\"100%\" cellspacing=\"0\" cellpadding=\"0\" style=\"border-collapse:separate;border-spacing:0;border:1px solid {{Mix(accentColor, backgroundColor, .25)}};border-radius:12px;font-size:13px;overflow:hidden\">{TQ});");
        sb.AppendLine("        var rows = content.Replace(\"\\r\\n\", \"\\n\").Split('\\n', StringSplitOptions.RemoveEmptyEntries).Take(100).ToArray();");
        sb.AppendLine("        for (var i = 0; i < rows.Length; i++)");
        sb.AppendLine("        {");
        sb.AppendLine("            html.Append(\"<tr>\");");
        sb.AppendLine("            var bg = tableStyle switch");
        sb.AppendLine("            {");
        sb.AppendLine("                \"accent\" when i == 0 => accentColor,");
        sb.AppendLine("                \"striped\" when i % 2 == 1 => Mix(accentColor, backgroundColor, .09),");
        sb.AppendLine("                \"classic\" when i == 0 => Mix(accentColor, backgroundColor, .12),");
        sb.AppendLine("                _ => backgroundColor");
        sb.AppendLine("            };");
        sb.AppendLine("            var txt = tableStyle == \"accent\" && i == 0 ? ContrastText(accentColor) : textColor;");
        sb.AppendLine("            foreach (var cell in rows[i].Split('|').Take(12))");
        sb.AppendLine($"                html.Append(${TQ}<td style=\"padding:11px 12px;background:{{bg}};color:{{txt}};border-bottom:1px solid {{Mix(accentColor, backgroundColor, .18)}};{{(i == 0 ? \"font-weight:bold;\" : \"\")}}\">{{E(cell.Trim())}}</td>{TQ});");
        sb.AppendLine("            html.Append(\"</tr>\");");
        sb.AppendLine("        }");
        sb.AppendLine("        html.Append(\"</table>\");");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static void RenderChart(StringBuilder html, string title, string content, string chartType, string backgroundColor, string textColor, string accentColor)");
        sb.AppendLine("    {");
        sb.AppendLine("        var rows = content.Replace(\"\\r\\n\", \"\\n\").Split('\\n', StringSplitOptions.RemoveEmptyEntries)");
        sb.AppendLine("            .Select(line => line.Split(','))");
        sb.AppendLine("            .Where(parts => parts.Length >= 2 && double.TryParse(parts[1].Trim(), NumberStyles.Float, CultureInfo.InvariantCulture, out var v) && double.IsFinite(v) && v >= 0)");
        sb.AppendLine("            .Take(50).Select(parts => (Label: parts[0].Trim(), Value: double.Parse(parts[1].Trim(), CultureInfo.InvariantCulture), Forecast: parts.Length > 2 && parts[2].Trim().Equals(\"forecast\", StringComparison.OrdinalIgnoreCase))).ToList();");
        sb.AppendLine("        var max = rows.Count == 0 ? 0 : rows.Max(r => r.Value);");
        sb.AppendLine($"        html.Append(${TQ}<h2 style=\"font-size:19px;margin:0 0 14px;color:{{textColor}}\">{{E(title)}}</h2>{TQ});");
        sb.AppendLine("        if (rows.Count > 0 && chartType is \"line chart\" or \"area chart\")");
        sb.AppendLine("            RenderLineVisual(html, chartType, rows.Select(r => r.Value).ToList(), max, textColor, accentColor);");
        sb.AppendLine("        else if (rows.Count > 0 && chartType is \"pie chart\" or \"doughnut chart\")");
        sb.AppendLine("            RenderPieVisual(html, chartType, rows.Select(r => r.Value).ToList(), max, backgroundColor, accentColor);");
        sb.AppendLine("        html.Append(\"<table width=\\\"100%\\\" cellspacing=\\\"0\\\" cellpadding=\\\"4\\\" style=\\\"font-size:13px;border-collapse:collapse\\\">\");");
        sb.AppendLine("        for (var index = 0; index < rows.Count; index++)");
        sb.AppendLine("        {");
        sb.AppendLine("            var row = rows[index];");
        sb.AppendLine("            var width = max > 0 ? Math.Clamp((int)Math.Round(row.Value / max * 100), 0, 100) : 0;");
        sb.AppendLine("            var forecast = chartType == \"forecast chart\" && row.Forecast;");
        sb.AppendLine($"            html.Append(${TQ}<tr><td width=\"25%\">{{E(row.Label)}}{{(forecast ? \" (forecast)\" : \"\")}}</td>{TQ});");
        sb.AppendLine("            if (chartType is \"bar chart\" or \"comparison chart\" or \"forecast chart\")");
        sb.AppendLine($"                html.Append(${TQ}<td width=\"60%\"><table role=\"presentation\" width=\"100%\" cellspacing=\"0\" cellpadding=\"0\"><tr><td width=\"{{width}}%\" style=\"height:12px;background:{{SliceColor(accentColor, forecast ? 2 : index)}};border-radius:6px\"></td><td></td></tr></table></td>{TQ});");
        sb.AppendLine("            else if (chartType is \"pie chart\" or \"doughnut chart\")");
        sb.AppendLine($"                html.Append(${TQ}<td><span style=\"display:inline-block;width:12px;height:12px;background:{{SliceColor(accentColor, index)}}\"></span></td>{TQ});");
        sb.AppendLine($"            html.Append(${TQ}<td align=\"right\">{{row.Value.ToString(\"0.##\", CultureInfo.InvariantCulture)}}</td></tr>{TQ});");
        sb.AppendLine("        }");
        sb.AppendLine("        if (rows.Count == 0) html.Append(\"<tr><td>Add chart data as label,value, one row per line.</td></tr>\");");
        sb.AppendLine("        html.Append(\"</table>\");");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static void RenderLineVisual(StringBuilder html, string chartType, List<double> values, double max, string textColor, string accentColor)");
        sb.AppendLine("    {");
        sb.AppendLine("        var points = values.Select((value, i) => (X: values.Count == 1 ? 250.0 : 20.0 + 460.0 * i / (values.Count - 1), Y: 150.0 - (max > 0 ? value / max * 130.0 : 0))).ToList();");
        sb.AppendLine("        var coordinates = string.Join(\" \", points.Select(p => $\"{F(p.X)},{F(p.Y)}\"));");
        sb.AppendLine($"        html.Append(${TQ}<svg xmlns=\"http://www.w3.org/2000/svg\" role=\"img\" viewBox=\"0 0 500 170\" width=\"500\" style=\"display:block;width:100%;max-width:500px;height:auto\">{TQ});");
        sb.AppendLine($"        html.Append(${TQ}<line x1=\"20\" y1=\"150\" x2=\"480\" y2=\"150\" stroke=\"{{textColor}}\" stroke-opacity=\".25\"/>{TQ});");
        sb.AppendLine("        if (chartType == \"area chart\" && points.Count > 1)");
        sb.AppendLine($"            html.Append(${TQ}<polygon points=\"20,150 {{coordinates}} 480,150\" fill=\"{{accentColor}}\" fill-opacity=\".25\"/>{TQ});");
        sb.AppendLine("        if (points.Count > 1)");
        sb.AppendLine($"            html.Append(${TQ}<polyline points=\"{{coordinates}}\" fill=\"none\" stroke=\"{{accentColor}}\" stroke-width=\"3\"/>{TQ});");
        sb.AppendLine("        foreach (var point in points)");
        sb.AppendLine($"            html.Append(${TQ}<circle cx=\"{{F(point.X)}}\" cy=\"{{F(point.Y)}}\" r=\"4\" fill=\"{{accentColor}}\"/>{TQ});");
        sb.AppendLine("        html.Append(\"</svg>\");");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    private static void RenderPieVisual(StringBuilder html, string chartType, List<double> values, double max, string backgroundColor, string accentColor)");
        sb.AppendLine("    {");
        sb.AppendLine($"        html.Append(${TQ}<svg xmlns=\"http://www.w3.org/2000/svg\" role=\"img\" viewBox=\"0 0 120 120\" width=\"180\" height=\"180\" style=\"display:block;max-width:100%;height:auto;margin:0 auto\">{TQ});");
        sb.AppendLine("        var total = max > 0 ? values.Sum(v => v / max) : 0;");
        sb.AppendLine("        if (total == 0)");
        sb.AppendLine($"            html.Append(${TQ}<circle cx=\"60\" cy=\"60\" r=\"50\" fill=\"{{backgroundColor}}\" stroke=\"{{accentColor}}\"/>{TQ});");
        sb.AppendLine("        var angle = -Math.PI / 2;");
        sb.AppendLine("        for (var i = 0; i < values.Count && total > 0; i++)");
        sb.AppendLine("        {");
        sb.AppendLine("            var fraction = (values[i] / max) / total;");
        sb.AppendLine("            if (fraction <= 0) continue;");
        sb.AppendLine("            var end = angle + fraction * Math.PI * 2;");
        sb.AppendLine("            var x1 = 60 + 50 * Math.Cos(angle); var y1 = 60 + 50 * Math.Sin(angle);");
        sb.AppendLine("            var x2 = 60 + 50 * Math.Cos(end); var y2 = 60 + 50 * Math.Sin(end);");
        sb.AppendLine("            var color = SliceColor(accentColor, i);");
        sb.AppendLine("            if (fraction >= 0.999999999)");
        sb.AppendLine($"                html.Append(${TQ}<circle cx=\"60\" cy=\"60\" r=\"50\" fill=\"{{color}}\"/>{TQ});");
        sb.AppendLine("            else");
        sb.AppendLine($"                html.Append(${TQ}<path d=\"M 60 60 L {{F(x1)}} {{F(y1)}} A 50 50 0 {{(fraction > .5 ? 1 : 0)}} 1 {{F(x2)}} {{F(y2)}} Z\" fill=\"{{color}}\"/>{TQ});");
        sb.AppendLine("            angle = end;");
        sb.AppendLine("        }");
        sb.AppendLine("        if (chartType == \"doughnut chart\")");
        sb.AppendLine($"            html.Append(${TQ}<circle cx=\"60\" cy=\"60\" r=\"27\" fill=\"{{backgroundColor}}\"/>{TQ});");
        sb.AppendLine("        html.Append(\"</svg>\");");
        sb.AppendLine("    }");
        sb.AppendLine();
